// brand/logo/source -> brand/logo/svg: every lockup in Black and White, split from the given paths, never redrawn.
// The source is the site's combination mark (AGD public/agd-lockup.svg, 630x110): its last path is the square
// logomark (64x64 at 0,24) and the first eight the wordmark (116 to 630 across). The site's own files place them the
// same way: public/logo.svg (the square alone), public/agd-wordmark.svg (viewBox 116 0 514 110). The liquid-glass mark
// (public/logo-glass.svg) is copied as is: it is a picture, not a one-color mark.
//
//   node scripts/make-logos.mjs
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..');
const src = (f) => readFileSync(join(root, 'brand', 'logo', 'source', f), 'utf8');
const paths = (svg) => [...svg.matchAll(/<path\b[^>]*\/>/g)].map((m) => m[0].replace(/\s*fill="[^"]*"/, ''));

const all = paths(src('lockup.svg'));
const mark = all.slice(-1);
const word = all.slice(0, -1);

// Bounding boxes in the source's units (the square is 64 by 64 at 0,24; the wordmark runs 116 to 630 and 0 to 110,
// the box the site's agd-wordmark.svg crops to).
const BOX = {
	mark: { x: 0, y: 24, w: 64, h: 64 },
	word: { x: 116, y: 0, w: 514, h: 110 },
};
const n = (v) => +v.toFixed(4);
const group = (ps, box, x, y, w) => {
	const s = w / box.w;
	return `<g transform="translate(${n(x)} ${n(y)}) scale(${n(s)}) translate(${n(-box.x)} ${n(-box.y)})">${ps.join('')}</g>`;
};
const svg = (w, h, body, fill, title) => `<svg xmlns="http://www.w3.org/2000/svg" width="${n(w)}" height="${n(h)}" viewBox="0 0 ${n(w)} ${n(h)}" fill="${fill}" role="img" aria-label="${title}"><title>${title}</title>${body}</svg>\n`;

const lockups = {
	// The square alone (the site's public/logo.svg is the same square at 600).
	mark: { w: BOX.mark.w, h: BOX.mark.h, body: group(mark, BOX.mark, 0, 0, BOX.mark.w), title: 'Agencidev logomark' },
	// The wordmark alone (public/agd-wordmark.svg).
	wordmark: { w: BOX.word.w, h: BOX.word.h, body: group(word, BOX.word, 0, 0, BOX.word.w), title: 'Agencidev' },
	// The combination mark as given (630x110): the nav bar's and the footer's lockup.
	horizontal: { w: 630, h: 110, body: all.join(''), title: 'Agencidev' },
};

const out = join(root, 'brand', 'logo', 'svg');
mkdirSync(out, { recursive: true });
const written = [];
for (const [name, l] of Object.entries(lockups)) {
	for (const [tone, fill] of [['black', '#000000'], ['white', '#FFFFFF']]) {
		writeFileSync(join(out, `${name}-${tone}.svg`), svg(l.w, l.h, l.body, fill, l.title));
		written.push(`${name}-${tone}.svg`);
	}
}
copyFileSync(join(root, 'brand', 'logo', 'source', 'mark-glass.svg'), join(out, 'mark-glass.svg'));
written.push('mark-glass.svg');
// The favicon and the avatars: the white square on black (the site's app/icon.png is the white square on black).
const square = (size, share, ground, fill) => {
	const w = size * share;
	return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}"><rect width="${size}" height="${size}" fill="${ground}"/><g fill="${fill}">${group(mark, BOX.mark, (size - w) / 2, (size - w) / 2, w)}</g></svg>\n`;
};
writeFileSync(join(out, 'favicon.svg'), square(64, 0.5, '#000000', '#FFFFFF'));
writeFileSync(join(out, 'avatar-black.svg'), square(600, 0.4, '#000000', '#FFFFFF'));
writeFileSync(join(out, 'avatar-white.svg'), square(600, 0.4, '#FFFFFF', '#000000'));
written.push('favicon.svg', 'avatar-black.svg', 'avatar-white.svg');
// The same lockups for the library (registry/lib/logos.ts): each one's size and its paths, filled by currentColor.
const lib = Object.entries(lockups).map(([name, l]) => `\t'${name}': { width: ${n(l.w)}, height: ${n(l.h)}, body: ${JSON.stringify(l.body)} },`).join('\n');
writeFileSync(join(root, 'registry', 'lib', 'logos.ts'), `// Generated by scripts/make-logos.mjs from brand/logo/source (the site's agd-lockup.svg): every lockup's size and
// paths, split from the given paths, never redrawn. Fill them with currentColor in black or white only.
export type LogoVariant = ${Object.keys(lockups).map((k) => `'${k}'`).join(' | ')}
export const LOGO_VARIANTS: LogoVariant[] = [${Object.keys(lockups).map((k) => `'${k}'`).join(', ')}]
export const LOGOS: Record<LogoVariant, { width: number; height: number; body: string }> = {
${lib}
}
`);
console.log(`logos: ${written.length} files -> brand/logo/svg, registry/lib/logos.ts`);
